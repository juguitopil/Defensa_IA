    public static DefinicionPermiso? Buscar(string clave) =>
        Todos.FirstOrDefault(p => p.Clave.Equals(clave.Trim(), StringComparison.OrdinalIgnoreCase));

    public static DefinicionPermiso Resolver(string clave)
    {
        var limpia = clave.Trim();
        return Buscar(limpia) ?? new DefinicionPermiso(
            limpia,
            limpia,
            "Este permiso no está en el catálogo. Se revisa con sensibilidad media hasta clasificarlo.",
            "no tiene una consecuencia descrita en el catálogo",
            NivelRiesgo.Medio,
            ["desconocido"]);
    }

    private static DefinicionPermiso Def(
        string clave,
        string nombre,
        string descripcion,
        string consecuencia,
        NivelRiesgo nivel,
        params string[] propositos) =>
        new(clave, nombre, descripcion, consecuencia, nivel, propositos);
